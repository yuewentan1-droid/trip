const banks = new Map();
const built = key => {
  if (!banks.has(key)) {
    banks.set(key, DETAILS[key].flatMap(d => FRAMES.map(f => f.replace('{d}', d))));
  }
  return banks.get(key);
};

let all;
const hookBank = topic => {
  const key = Object.keys(DETAILS).find(k => topic?.includes(k));
  return key ? built(key) : (all ||= Object.keys(DETAILS).flatMap(built));
};

// 一个行当一副洗好的牌，抽完一轮才重洗；同一句不会连着冒出来
const decks = new Map();
let last = '';
export const drawHook = topic => {
  const bank = hookBank(topic);
  let deck = decks.get(bank);
  if (!deck?.length) {
    deck = bank.map((_, i) => i);
    for (let i = deck.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [deck[i], deck[j]] = [deck[j], deck[i]];
    }
    decks.set(bank, deck);
  }
  let i = deck.pop();
  if (bank[i] === last && deck.length) {
    deck.unshift(i);
    i = deck.pop();
  }
  last = bank[i];
  return last;
};
